def aff(i0, i1, l, pos, fct_txt, fct_c, aff_if_alone=True):
    l_cut = []
    size = get_aff_size("s_tick")*0.65
    dec = 0.3
    i0_save = i0
    for i in np.arange(i0,i1):
        if l[i] != l[i0]:
            #print i0, i, i0-dec,i-1+dec
            l_ax[1].text(0.5*(i0+i)-0.5,pos-0.02, tex(fct_txt(i0)), va="bottom", ha="center", size=size)
            l_ax[1].plot([i0-dec,i-1+dec],[pos,pos],c=fct_c(i0))
            l_cut += [(i0,i)]
            i0 = i
    if i0!=i0_save or aff_if_alone:
        l_ax[1].text(0.5*(i0+i+1)-0.5,pos-0.02, tex(fct_txt(i0)), va="bottom", ha="center", size=size)
        l_ax[1].plot([i0-dec,i+1-1+dec],[pos,pos],c=fct_c(i0))
        l_cut += [(i0,i+1)]
    else:
        l_cut += [(i0,i+1)]
    return l_cut

